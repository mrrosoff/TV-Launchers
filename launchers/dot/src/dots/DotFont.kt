package dev.mrrosoff.tv.dot.dots

import java.text.Normalizer

/** A 5x7 LED font. Each glyph is seven rows of five cells, lowest bit on the right. */
object DotFont {
    const val COLS = 5
    const val ROWS = 7
    /** One blank column between glyphs. */
    const val ADVANCE = COLS + 1

    private val glyphs: Map<Char, IntArray> = mapOf(
        'A' to g(".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"),
        'B' to g("####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."),
        'C' to g(".###.", "#...#", "#....", "#....", "#....", "#...#", ".###."),
        'D' to g("####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####."),
        'E' to g("#####", "#....", "#....", "####.", "#....", "#....", "#####"),
        'F' to g("#####", "#....", "#....", "####.", "#....", "#....", "#...."),
        'G' to g(".###.", "#...#", "#....", "#.###", "#...#", "#...#", ".####"),
        'H' to g("#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"),
        'I' to g(".###.", "..#..", "..#..", "..#..", "..#..", "..#..", ".###."),
        'J' to g("..###", "...#.", "...#.", "...#.", "...#.", "#..#.", ".##.."),
        'K' to g("#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#"),
        'L' to g("#....", "#....", "#....", "#....", "#....", "#....", "#####"),
        'M' to g("#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#"),
        'N' to g("#...#", "#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#"),
        'O' to g(".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."),
        'P' to g("####.", "#...#", "#...#", "####.", "#....", "#....", "#...."),
        'Q' to g(".###.", "#...#", "#...#", "#...#", "#.#.#", "#..#.", ".##.#"),
        'R' to g("####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"),
        'S' to g(".####", "#....", "#....", ".###.", "....#", "....#", "####."),
        'T' to g("#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."),
        'U' to g("#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."),
        'V' to g("#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#.."),
        'W' to g("#...#", "#...#", "#...#", "#.#.#", "#.#.#", "#.#.#", ".#.#."),
        'X' to g("#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#"),
        'Y' to g("#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#.."),
        'Z' to g("#####", "....#", "...#.", "..#..", ".#...", "#....", "#####"),
        '0' to g(".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###."),
        '1' to g("..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###."),
        '2' to g(".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####"),
        '3' to g("#####", "...#.", "..#..", "...#.", "....#", "#...#", ".###."),
        '4' to g("...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#."),
        '5' to g("#####", "#....", "####.", "....#", "....#", "#...#", ".###."),
        '6' to g("..##.", ".#...", "#....", "####.", "#...#", "#...#", ".###."),
        '7' to g("#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#..."),
        '8' to g(".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###."),
        '9' to g(".###.", "#...#", "#...#", ".####", "....#", "...#.", ".##.."),
        ' ' to g(".....", ".....", ".....", ".....", ".....", ".....", "....."),
        '+' to g(".....", "..#..", "..#..", "#####", "..#..", "..#..", "....."),
        '-' to g(".....", ".....", ".....", "#####", ".....", ".....", "....."),
        '.' to g(".....", ".....", ".....", ".....", ".....", ".##..", ".##.."),
        ',' to g(".....", ".....", ".....", ".....", ".##..", "..#..", ".#..."),
        ':' to g(".....", ".##..", ".##..", ".....", ".##..", ".##..", "....."),
        '\'' to g("..#..", "..#..", ".#...", ".....", ".....", ".....", "....."),
        '&' to g(".##..", "#..#.", "#.#..", ".#...", "#.#.#", "#..#.", ".##.#"),
        '!' to g("..#..", "..#..", "..#..", "..#..", "..#..", ".....", "..#.."),
        '?' to g(".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#.."),
        '/' to g("....#", "....#", "...#.", "..#..", ".#...", "#....", "#...."),
        '(' to g("...#.", "..#..", ".#...", ".#...", ".#...", "..#..", "...#."),
        ')' to g(".#...", "..#..", "...#.", "...#.", "...#.", "..#..", ".#..."),
        '°' to g(".##..", "#..#.", "#..#.", ".##..", ".....", ".....", "....."),
        '·' to g(".....", ".....", ".....", "..#..", ".....", ".....", "....."),
    )

    /** Rows for [c]; accents are dropped and anything the font lacks shows as '?'. */
    fun glyph(c: Char): IntArray = glyphs[c] ?: glyphs[c.uppercaseChar()] ?: glyphs[plain(c)] ?: glyphs.getValue('?')

    fun normalize(text: String): String = text.uppercase()

    private fun plain(c: Char): Char =
        Normalizer.normalize(c.toString(), Normalizer.Form.NFD).firstOrNull()?.uppercaseChar() ?: '?'

    private fun g(vararg rows: String) = IntArray(ROWS) { r ->
        rows[r].fold(0) { bits, ch -> (bits shl 1) or (if (ch == '#') 1 else 0) }
    }
}
